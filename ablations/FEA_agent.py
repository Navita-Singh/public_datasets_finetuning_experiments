class FEAAgentState(TypedDict):
    task_description: str
    messages: List[Any]
    target_files: List[str]
    proposed_code_changes: Dict[str, str]
    safety_passed: bool
    execution_success: bool
    error_log: str
    iteration: int
    span_rewards: Dict[str, float]
    outcome_reward: float
    token_costs: Dict[str, int]
    progress_percentage: float

@traceable(name="Plan Amendments")
def plan_amendments(state: FEAAgentState) -> FEAAgentState:
    system_prompt = (
        "You are an expert FEA software engineer agent[cite: 1]. "
        "Modify FEA solver scripts based on requirements[cite: 1]. "
        "CRITICAL: Never modify 'src/utils.py' or 'Skills/FEA_skills'[cite: 1]."
    )
    user_prompt = state["messages"][-1].content if state["messages"] else state["task_description"]

    response_text = generate_with_qwen(system_prompt, user_prompt)
    state["messages"].append(AIMessage(content=response_text))

    state["token_costs"]["plan_span"] = len(response_text.split())
    state["span_rewards"]["span_1_planning"] = 1.0
    state["progress_percentage"] = 25.0
    return state

@traceable(name="Safety Guardrail Check")
def safety_guardrail_check(state: FEAAgentState) -> FEAAgentState:
    protected_files = ["utils.py", "FEA_skills"]
    target_files = state.get("target_files", [])

    for file in target_files:
        if any(p in file for p in protected_files):
            state["safety_passed"] = False
            state["error_log"] = f"Safety Violation: Unauthorized modification attempt on protected file '{file}'[cite: 1]."
            state["span_rewards"]["span_2_safety"] = 0.0
            state["progress_percentage"] = 50.0
            return state

    state["safety_passed"] = True
    state["error_log"] = ""
    state["span_rewards"]["span_2_safety"] = 1.0
    state["progress_percentage"] = 50.0
    return state

@traceable(name="Execute File Amendments")
def execute_file_amendments(state: FEAAgentState) -> FEAAgentState:
    try:
        for file_path, code_content in state.get("proposed_code_changes", {}).items():
            full_path = os.path.join("src", file_path) if not file_path.startswith("src/") else file_path
            with open(full_path, "w") as f:
                f.write(code_content)

        version_file = "src/version.py"
        if os.path.exists(version_file):
            with open(version_file, "a") as f:
                f.write("\n# Updated by Colab Agent[cite: 1]\n")

        state["execution_success"] = True
        state["span_rewards"]["span_3_file_update"] = 1.0
        state["progress_percentage"] = 75.0
    except Exception as e:
        state["execution_success"] = False
        state["error_log"] = str(e)
        state["span_rewards"]["span_3_file_update"] = 0.0
    return state

@traceable(name="Verify Solvers")
def verify_solvers(state: FEAAgentState) -> FEAAgentState:
    try:
        res_1d = subprocess.run(["python", "src/FEA_solver_1D.py"], capture_output=True, text=True, timeout=30)
        res_2d = subprocess.run(["python", "src/FEA_solver_2D.py"], capture_output=True, text=True, timeout=30)

        if res_1d.returncode == 0 and res_2d.returncode == 0:
            state["execution_success"] = True
            state["span_rewards"]["span_4_verification"] = 1.0
            state["outcome_reward"] = 1.0
            state["progress_percentage"] = 100.0
        else:
            state["execution_success"] = False
            state["error_log"] = f"1D: {res_1d.stderr}\n2D: {res_2d.stderr}"
            state["span_rewards"]["span_4_verification"] = 0.0
            state["outcome_reward"] = 0.0
    except Exception as e:
        state["execution_success"] = False
        state["error_log"] = str(e)
        state["span_rewards"]["span_4_verification"] = 0.0
        state["outcome_reward"] = 0.0
    return state

@traceable(name="Route After Safety")
def route_after_safety(state: FEAAgentState):
    if not state["safety_passed"]:
        return "handle_safety_violation"
    return "execute_amendments"

@traceable(name="Handle Safety Violation")
def handle_safety_violation(state: FEAAgentState) -> FEAAgentState:
    state["outcome_reward"] = 0.0
    state["messages"].append(AIMessage(content=f"HALTED: {state['error_log']}"))
    return state

